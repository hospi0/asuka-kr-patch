def blen(s):
    return sum(1 if ord(c) < 0x80 else 2 for c in ESC.sub('\x01', s))


def width(s):
    return max(len(ESC.sub('', x)) for x in s.split(N))


done = set()
for p in sorted(glob.glob(os.path.join(ROOT, 'my files', 'tsv2', '*.tsv'))):
    L = open(p, encoding='utf-8', newline='').read().split('\n'); ch = False
    for k, ln in enumerate(L):
        c = ln.split('\t')
        if len(c) < 7 or c[0] not in R:
            continue
        t = c[6]
        for a, b in R[c[0]]:
            if a not in t:
                print('  !! 조각 없음', c[0], repr(a)); break
            t = t.replace(a, b)
        else:
            pair = c[0] in ('SYS01447', 'SYS01448', 'SYS01467', 'SYS01468', 'SYS01479', 'SYS01480')   # 빌더가 쌍으로 묶는다
            ok = pair or (blen(t) <= int(c[3]) and width(t) <= max(width(c[6]), 20))
            print('OK ' if ok else '넘침', c[0], c[3], blen(t), width(t), '|', t.replace(N, ' / '))
            if ok:
                c[6] = t; L[k] = '\t'.join(c); ch = True; done.add(c[0])
    if ch and '--write' in sys.argv:
        open(p, 'w', encoding='utf-8', newline='').write('\n'.join(L))
print(len(done), '/', len(R))
