JOSA = [('가', '이'), ('는', '은'), ('를', '을'), ('와', '과'), ('로', '으로'), ('야', '이야'), ('여', '이여'), ('랑', '이랑')]


def nunim(s):
    def f(m):
        j = m.group(2) or ''
        for a, b in JOSA:
            if j == a: return '누님' + b
        return '누님' + j
    return re.sub(r'(언니|아씨|아네상)(가|는|를|와|로|야|여|랑)?', f, s)


def main():
    files = sorted(glob.glob(os.path.join(ROOT, 'my files', 'tsv2', '*.tsv')))
    out = {}; n = 0
    for p in files:
        lines = open(p, encoding='utf-8').read().split('\n'); ch = False
        for i, ln in enumerate(lines):
            c = ln.split('\t')
            if len(c) < 7 or c[0] == 'id': continue
            new = c[6]
            if c[0] in FIX: new = FIX[c[0]]
            elif 'アネさん' in c[5]: new = nunim(new)
            if new != c[6]:
                print('%s\n  %s\n→ %s' % (c[0], c[6], new)); c[6] = new; lines[i] = '\t'.join(c); ch = True; n += 1
        if ch: out[p] = '\n'.join(lines)
    miss = set(FIX) - {l.split('\t')[0] for p in files for l in open(p, encoding='utf-8')}
    print('바뀐 줄', n, '· 못 찾은 id', sorted(miss))
    if '--write' in sys.argv:
        bk = os.path.join(ROOT, 'work', 'tsv_backup_20261011'); os.makedirs(bk, exist_ok=True)
        for p, s in out.items():
            shutil.copy(p, os.path.join(bk, os.path.basename(p))); open(p, 'w', encoding='utf-8', newline='').write(s)
        print('썼음 · 백업', bk)


if __name__ == '__main__':
    main()
