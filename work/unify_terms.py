def bat(ch):
    o = ord(ch) - 0xAC00
    return 0 <= o < 11172 and o % 28 != 0


def fixjosa(text, word):
    """word 바로 뒤 조사를 word 마지막 글자 받침에 맞춤"""
    b = bat(word[-1]); out = text; pos = 0
    while True:
        i = out.find(word, pos)
        if i < 0:
            return out
        e = i + len(word)
        for a, c in JOSA:
            for have, want in ((a, a if b else c), (c, a if b else c)):
                if out.startswith(have, e) and have != want and (e + len(have) >= len(out) or not ('가' <= out[e + len(have)] <= '힣') or have in ('으로', '로')):
                    out = out[:e] + want + out[e + len(have):]; break
            else:
                continue
            break
        pos = e


def blen(s):
    return sum(1 if ord(c) < 0x80 else 2 for c in ESC.sub('\x01', s))


def width(line):
    return len(ESC.sub('', line))


