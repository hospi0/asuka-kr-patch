    L = open(p, encoding='utf-8', newline='').read().split('\n'); ch = False
    for k, ln in enumerate(L):
        c = ln.split('\t')
        if len(c) < 7 or c[0] not in R:
            continue
        rule = R[c[0]]; t = c[6]; miss = False
        if isinstance(rule, str):
            t = rule[5:].replace(BS + BS + 'n', N)
        else:
            for a, b in rule:
                if a not in t:
                    print('  !! 조각 없음', c[0], repr(a)); miss = True; break
                t = t.replace(a, b)
        if miss:
            continue
        ok = blen(t) <= int(c[3]) and width(t) <= max(width(c[6]), 20) and t.count(N) <= max(c[6].count(N), 9)
        print('OK ' if ok else '넘침', c[0], c[3], blen(t), width(t), t.count(N), '|', t.replace(N, ' / ')[:90])
        if ok:
            done.add(c[0])
            if t != c[6]:
                c[6] = t; L[k] = '\t'.join(c); ch = True
    if ch and '--write' in sys.argv:
        open(p, 'w', encoding='utf-8', newline='').write('\n'.join(L))
