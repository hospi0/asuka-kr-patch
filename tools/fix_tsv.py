def on_plain(s, fn):
    """보호 토큰은 그대로 두고 «본문 조각»에만 fn 을 적용한다."""
    out, i = [], 0
    for m in PROTECT.finditer(s):
        out.append(fn(s[i:m.start()]))
        out.append(m.group())
        i = m.end()
    out.append(fn(s[i:]))
    return ''.join(out)


