def undouble(s):
    """이중 이스케이프 되돌리기: \\u3000 -> 전각공백, \\\\ -> \\"""
    s = s.replace(BS + 'u3000', '　')
    return s.replace(BS + BS, BS)


def apply_rules(s, rules):
    for pat, rep in rules:
        s = pat.sub(rep, s)
    return s


def tighten(s, rules):
    """보호 토큰을 피해 축약 규칙을 적용한다."""
    return on_plain(s, lambda t: apply_rules(t, rules))


# ★«띄어쓰기 두세개» (사용자 지시 2026-08-28) — 줄당 상한.
#   실측으로 2 + «그 줄 공백의 절반»이 읽히는 한계였다. 상한을 3으로 올려도
#   남는 예산초과는 1,376 -> 1,374 구간으로 거의 안 줄고 문장만 나빠진다.
MAX_SPACE_PER_LINE = 2


def drop_spaces(s, need, per_line=MAX_SPACE_PER_LINE):
    """어절 공백을 «필요한 만큼만, 줄당 상한 안에서» 지운다. (지운 수, 결과)

    ★★상한이 없으면 긴 설명문의 공백을 통째로 먹어 «손에창을든주홍색물고기모습의»
      같은 못 읽는 문장이 된다. 실제로 한 번 그렇게 만들어 보고 되돌렸다.
      줄당 2~3칸까지가 읽히는 한계다.
    한글과 한글 사이 공백을 먼저 고른다(읽기 손상이 가장 적다).
    """
    if need <= 0:
        return 0, s
    prot = [(m.start(), m.end()) for m in PROTECT.finditer(s)]

    def inside(k):
        return any(a <= k < b for a, b in prot)

    # 줄 경계(\n 이스케이프)로 나눠 «줄마다» 상한을 건다
    bounds, prev = [], 0
    for m in re.finditer(re.escape(BS) + 'n', s):
        bounds.append((prev, m.start()))
        prev = m.end()
    bounds.append((prev, len(s)))

    # ★★상한은 «개수»만으로는 부족하다 — 공백이 3칸뿐인 줄에서 2칸을 빼면 그 줄이
    #   통째로 붙어 버린다(「쿠로마루는카리기누에사시누키차림에」). 그래서
    #   «그 줄 공백의 1/3» 과 per_line 중 작은 쪽으로 «비례 상한»을 건다.
    def quota(a, b):
        n = sum(1 for k in range(a, b) if s[k] == ' ' and not inside(k))
        # 그 줄 공백의 절반까지. 단 공백이 1칸뿐인 짧은 줄(「대형 지뢰」류 합성어)은
        # 그 한 칸을 지워도 읽히므로 최소 1칸은 허용한다 — +1B 초과가 대부분 이 경우다.
        return min(per_line, max(1, n // 2))

    kill = set()
    for pref in (True, False):                 # 한글 사이 -> 그 밖
        for a, b in bounds:
            room = quota(a, b) - sum(1 for k in kill if a <= k < b)
            if room <= 0:
                continue
            cand = []
            for k in range(a, b):
                if s[k] != ' ' or k in kill or inside(k):
                    continue
                x = s[k - 1] if k else ''
                y = s[k + 1] if k + 1 < len(s) else ''
                if (('가' <= x <= '힣') and ('가' <= y <= '힣')) == pref:
                    cand.append(k)
            for k in reversed(cand):
                if len(kill) >= need or room <= 0:
                    break
                kill.add(k)
                room -= 1
            if len(kill) >= need:
                break
        if len(kill) >= need:
            break
    if not kill:
        return 0, s
    return len(kill), ''.join(c for k, c in enumerate(s) if k not in kill)


