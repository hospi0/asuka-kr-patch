# ★★공백을 «개행으로 바꾸는» 것이므로 바이트가 안 변한다(둘 다 1 B).
#   그래서 예산 작업을 끝낸 뒤에 돌려도 예산이 다시 깨지지 않는다.
#   ⛔자리가 없어 개행을 «끼워 넣어야» 하면 1 B 가 늘어난다 — 그건 하지 않고 남긴다.
def kr_cells(line):
    """번역문 한 줄의 화면 폭(반칸). 이스케이프는 폭 0.

    ★★렌더러가 **고정폭**이라 반각도 전각 한 칸을 먹는다 — `B.byte_cells` 주석 참고.
    """
    return len(RAWCTRL.sub('', ESC_ALL.sub('', line))) * 2


#   ★★예산 축약이 «어절 공백»을 지워 놓은 줄은 접을 자리가 아예 없다
#     (「쏘는몬스터로,보야계」). 그런 줄은 **문장부호 뒤**에서 접는다.
#     ⚠부호 뒤 접기는 개행을 «끼워 넣는» 것이라 1 B 가 는다 — 쓰고 나서
#       구간이 넘치면 그 구간의 행을 통째로 되돌린다(⑤-b 단계).
PUNCT_BREAK = '.,!?…」』~'


def _pieces(line):
    """접을 수 있는 자리로 쪼갠다 — (조각, 앞에 붙일 구분자).

    구분자가 `' '` 면 그 자리 접기는 «공백→개행»이라 바이트 중립,
    `''` 면 개행을 끼워 넣는 것이라 1 B 가 는다.
    """
    out, cur, sep = [], '', ''
    for i, c in enumerate(line):
        if c == ' ':
            out.append((cur, sep))
            cur, sep = '', ' '
            continue
        cur += c
        if c in PUNCT_BREAK and i + 1 < len(line) and line[i + 1] != ' ':
            out.append((cur, sep))
            cur, sep = '', ''
    if cur:
        out.append((cur, sep))
    return [p for p in out if p[0]]


def wrap_line(line, limit, punct=False):
    """한 줄을 limit 안으로 접는다. 기본은 «공백 자리»에서만."""
    if kr_cells(line) <= limit:
        return [line]
    if not punct:
        if ' ' not in line:
            return [line]
        ps = [(p, ' ') for p in line.split(' ')]
    else:
        ps = _pieces(line)
    if len(ps) <= 1:
        return [line]
    out, cur = [], None
    for p, sep in ps:
        if cur is None:
            cur = p
            continue
        cand = cur + sep + p
        if kr_cells(cand) > limit:
            out.append(cur)
            cur = p
        else:
            cur = cand
    if cur is not None:
        out.append(cur)
    return out


# ★★원문은 «낱말 중간»에서 강제 개행돼 있다(`エ\nレキ箱`). 번역문도 그 구조를 물려받은
#   줄이 있어서, 줄을 통째로 이어 붙일 때 공백을 넣으면 낱말이 쪼개진다(「사랑스 러움」).
#   그래서 «이어 붙여도 안전한 줄»만 골라 재배치한다.
#   판정: 그 줄이 낱말·구가 끝나는 꼴로 맺혔는가.
# ★어미 목록으로 판정하면 반드시 샌다(「약한」「특징인」이 빠져 161행이 막혔다).
#   대신 **코퍼스에서 그 토막이 실제로 낱말로 쓰이는가**를 본다.
#   줄 끝 토막은 «후보»일 뿐이고, 줄 중간에 한 번이라도 나오면 «진짜 낱말»이다.
CONFIRMED = set()


def build_confirmed(files):
    """줄 «중간»에 나오는 토막 = 홀로 설 수 있는 낱말."""
    CONFIRMED.clear()
    for rows in files.values():
        for r in rows:
            if not r['kr'].strip():
                continue
            for line in split_lines(r['kr']):
                toks = ESC_ALL.sub(' ', line).split()
                CONFIRMED.update(toks[:-1])      # 마지막 토막은 줄바꿈에 잘렸을 수 있다


# 어미 목록만으로도, 코퍼스만으로도 각각 샌다(전자는 「약한」을, 후자는 줄 끝에만 나오는
# 낱말을 놓친다). 둘 중 하나라도 통과하면 «낱말이 끝난 자리»로 본다.
SAFE_END = re.compile(
    r'(?:[다요까죠네군지고며서만나은는이가을를의에로와과도여라자오'
    r'한인린면어아해니데게세운든뿐텐것들중때본새'
    r'.,!?…」』\)~・\-]|[0-9A-Za-z])$')


def word_end(line):
    """그 줄이 «낱말이 끝난 자리»에서 맺혔는가."""
    t = ESC_ALL.sub(' ', line).split()
    if not t:
        return True
    return t[-1] in CONFIRMED or bool(SAFE_END.search(t[-1]))


def flatten(lines):
    """줄들을 한 줄로 이어 붙인다.

    ★★낱말이 끝난 자리면 공백으로, 낱말 중간이면 «그대로» 붙인다.
      원문이 고정폭으로 강제 개행돼 있어 번역문에도 「두\\n꺼비」 같은 자리가 있다.
      전부 공백으로 이으면 낱말이 쪼개지고, 전부 붙이면 낱말이 엉겨붙는다.
    """
    out = lines[0]
    for nxt in lines[1:]:
        if not nxt:
            continue
        out = out + (' ' if word_end(out) else '') + nxt
    return out


def rewrap(kr, jp, limit, punct=False):
    """넘치는 줄을 다시 접는다. 줄 수는 원문을 넘지 않는다(대사창 높이).

    ①줄마다 따로 접어 본다 → 줄 수가 남으면 그걸로 끝.
    ②모자라면 «전체 재배치» — 단 이어 붙여도 안전한 줄일 때만 한다.
    둘 다 공백 자리에서만 접으므로 **바이트가 안 변한다**.
    """
    lines = split_lines(kr)
    if all(kr_cells(l) <= limit for l in lines):
        return kr
    maxlines = len(split_lines(jp))

    out = []
    for l in lines:
        out.extend(wrap_line(l, limit, punct))
    if len(out) <= maxlines and all(kr_cells(l) <= limit for l in out):
        return (BS + 'n').join(out)

    # ⛔`.strip()` 을 인수 없이 쓰면 안 된다 — 파이썬은 `\x1c`~`\x1f` 를 «공백»으로 봐서
    #   줄 끝의 «날 제어코드»(연출 대기 \x1F\x1E)를 통째로 먹는다. 지울 건 공백뿐이다.
    flat = flatten([l.strip(' 　') for l in lines])
    out = wrap_line(flat, limit, punct)
    if len(out) <= maxlines and all(kr_cells(l) <= limit for l in out):
        return (BS + 'n').join(out)
    return kr


def split_lines(s):
    """`\\\\`(진짜 백슬래시)를 먼저 치우고 `\\n` 으로 쪼갠다."""
    s = s.replace(BS + BS, '')
    return [p.replace('', BS + BS) for p in s.split(BS + 'n')]


