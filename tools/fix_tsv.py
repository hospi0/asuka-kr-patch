# --- 조사 교정 ---------------------------------------------------------------
# ★★용어를 바꾸면 «받침»이 달라져 뒤따르는 조사가 틀린다.
#   와라반을 -> 회보«을»(X, 회보를) / 삼파채로 -> 삼파성«로»(X, 삼파성으로)
#   지팡이를 -> 봉«를»(X, 봉을) / 대장장이는 -> 대장간«는»(X, 대장간은)
#   치환한 자리 «바로 뒤»에 붙은 조사만 고친다(띄어쓰기가 있으면 조사가 아니다).
ESC_ALL = re.compile(r'\\x[0-9A-Fa-f]{2}|\\n|\\t|\\\\')
# ★번역표엔 이스케이프 표기와 «날 제어문자»가 섞여 있다. 폭을 잴 땐 둘 다 0으로 본다.
RAWCTRL = re.compile(r'[\x00-\x1f\x7f]')


def blen(s):
    """cp932 로 인코딩했을 때의 바이트 수 (한글·전각 2, 반각 1)."""
    return sum(1 if ord(c) < 0x80 else 2 for c in s)

PARTICLES = [('으로', '로'), ('이라고', '라고'), ('이란', '란'), ('이나', '나'),
             ('이야', '야'), ('이에요', '예요'), ('이었', '였'),
             ('은', '는'), ('을', '를'), ('이', '가'), ('과', '와')]


def has_batchim(ch):
    """한글 음절의 받침 유무. 한글이 아니면 None."""
    if not ('가' <= ch <= '힣'):
        return None
    return (ord(ch) - 0xAC00) % 28 != 0


def _found(a, text, i=0):
    """a 는 문자열 또는 컴파일된 정규식. (시작, 끝) 또는 None."""
    if hasattr(a, 'search'):
        m = a.search(text, i)
        return (m.start(), m.end()) if m else None
    k = text.find(a, i)
    return (k, k + len(a)) if k >= 0 else None


def sub_word(text, a, b):
    """a -> b 로 바꾸되 «바로 뒤에 붙은 조사»를 새 받침에 맞게 고친다.

    ⚠a 에 «띄어쓴 변형»이 있으면 문자열 목록으로는 반드시 새어 나간다
      (원본에 「엘레키 박스」·「일렉 박스」가 있어 43행을 놓쳤다).
      여러 표기를 한꺼번에 덮어야 하는 낱말은 **정규식**으로 준다.
    """
    if _found(a, text) is None:
        return text
    bat = has_batchim(b[-1]) if b else None
    out, i = [], 0
    while True:
        hit = _found(a, text, i)
        if hit is None:
            out.append(text[i:])
            break
        k, end = hit
        out.append(text[i:k])
        out.append(b)
        j = end
        if bat is not None:
            for p_bat, p_no in PARTICLES:
                for form in (p_bat, p_no):
                    if text.startswith(form, j):
                        out.append(p_bat if bat else p_no)
                        j += len(form)
                        break
                else:
                    continue
                break
        i = j
    return ''.join(out)


